import type { Appointment, Doctor } from "./types";

export const CHAT_TEMPLATES = [
  "Уточнить дозировку препарата",
  "Появился побочный эффект",
  "Нет улучшения",
  "Когда можно вернуться к спорту?",
  "Нужна справка или больничный",
];

function firstName(doctor: Doctor): string {
  const [, name, patronymic] = doctor.name.split(" ");
  return [name, patronymic].filter(Boolean).join(" ");
}

export function chatGreeting(appt: Appointment, doctor: Doctor): string {
  return `Здравствуйте! Это ${firstName(doctor)}, ${doctor.specialty.toLowerCase()}. Я на связи по итогам приёма (${appt.diagnosis ?? "без диагноза"}). Напишите, что беспокоит.`;
}

/** Rule-based auto-reply from the treating doctor. */
export function doctorReply(text: string, appt: Appointment): string {
  const t = text.toLowerCase();
  const rx = appt.prescriptions?.trim();
  if (/(побочн|сып|аллерг|зуд|отёк|отек|тошн)/.test(t)) {
    return "Спасибо, что сообщили. Если появились отёк лица или губ, затруднённое дыхание или сыпь по всему телу — прекратите приём препарата и сразу звоните 103. При лёгких проявлениях пока не принимайте последний назначенный препарат и пришлите фото или описание — я подберу замену.";
  }
  if (/(дозир|доз[ау]|сколько раз|как принимать|мг)/.test(t)) {
    return rx
      ? `Напоминаю схему из заключения: ${rx} Не меняйте дозировку самостоятельно. Если сложно соблюдать режим — напишите, скорректируем.`
      : "В заключении нет лекарственных назначений. Если вы начали что-то принимать самостоятельно — напишите название и дозировку.";
  }
  if (/(не улучш|нет улучш|хуже|не проход|не помога)/.test(t)) {
    return "Понимаю. Если улучшения нет 3–5 дней или стало хуже — рекомендую повторный очный приём: нажмите «Повторный приём» в карточке визита. При высокой температуре, одышке или сильной боли обратитесь срочно (103).";
  }
  if (/(спорт|трениров|нагрузк|бассейн)/.test(t)) {
    return "Возвращайтесь к нагрузкам постепенно, не раньше чем через 3–5 дней после исчезновения симптомов. Начните с 50% привычного объёма.";
  }
  if (/(справк|больничн|лист нетрудоспособ)/.test(t)) {
    return "Электронный лист нетрудоспособности оформляется по итогам очного осмотра. Укажите период, и я подготовлю документ — он появится в вашем личном кабинете egov.";
  }
  return "Спасибо за сообщение, я его изучила. Продолжайте лечение по назначенной схеме. Если появятся новые симптомы — напишите или запишитесь на повторный приём.";
}

export function repeatVisitComplaint(appt: Appointment, dateLabel: string): string {
  return [
    `Повторный приём по диагнозу: ${appt.diagnosis ?? "—"}.`,
    `Предыдущий визит: ${dateLabel}.`,
    appt.prescriptions ? `Назначения: ${appt.prescriptions}` : null,
    "Динамика после лечения: ",
  ]
    .filter(Boolean)
    .join("\n");
}
